"""
Pydantic models for safe recovery actions, safety governor decisions,
verification probes, and the audit timeline.
"""

from datetime import datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class RecoveryActionType(str, Enum):
    """Allowlisted safe actions and explicitly forbidden actions."""
    # Pre-approved safe recovery actions (Allowlist)
    RESTORE_BASELINE_CONFIG = "restore_baseline_config"
    RECONNECT_DATABASE = "reconnect_database"
    CLEAR_LATENCY_DELAY = "clear_latency_delay"
    RESTART_SERVICE = "restart_service"

    # Explicitly forbidden/destructive actions (Tested to prove governor blocks them)
    DROP_DATABASE = "drop_database"
    DELETE_ALL_PATIENTS = "delete_all_patients"
    RUN_SHELL_COMMAND = "run_shell_command"
    MODIFY_SYSTEM_FILES = "modify_system_files"


# Strict Allowlist of permissible actions
ALLOWED_RECOVERY_ACTIONS: set[str] = {
    RecoveryActionType.RESTORE_BASELINE_CONFIG.value,
    RecoveryActionType.RECONNECT_DATABASE.value,
    RecoveryActionType.CLEAR_LATENCY_DELAY.value,
    RecoveryActionType.RESTART_SERVICE.value,
}

# Maximum recovery attempts permitted per incident cycle
MAX_RECOVERY_ATTEMPTS = 3


class ActionProposal(BaseModel):
    """
    A proposed recovery action, typically generated by an AI investigator or operator.
    Uses string for action_type so the safety governor can inspect and reject
    arbitrary or invalid inputs rather than failing at request parsing.
    """
    action_type: str = Field(min_length=1, description="Name of the proposed recovery action")
    parameters: dict[str, Any] = Field(default_factory=dict, description="Action arguments")
    rationale: str = Field(min_length=1, max_length=500, description="Why this action is proposed")
    supporting_evidence: list[str] = Field(
        default_factory=list,
        description="Keys or summaries of diagnostic evidence justifying this action",
    )
    attempt_number: int = Field(default=1, ge=1, description="Current recovery attempt count (max 3)")


class GovernorDecision(BaseModel):
    """Deterministic validation outcome from the Safety Governor."""
    approved: bool
    action_type: str
    attempt_number: int
    reason: str
    requires_human_escalation: bool = False
    timestamp: datetime


class ExecutionResult(BaseModel):
    """Result of executing an approved recovery action against the simulator."""
    executed: bool
    action_type: str
    message: str
    timestamp: datetime


class VerificationResult(BaseModel):
    """Proof that a recovery action actually restored system health."""
    verified: bool
    health_ok: bool
    database_ok: bool
    latency_ok: bool
    booking_test_ok: bool
    details: str
    timestamp: datetime


class RecoveryCycleOutcome(BaseModel):
    """Consolidated outcome of the propose -> govern -> execute -> verify pipeline."""
    proposal: ActionProposal
    governor_decision: GovernorDecision
    execution_result: ExecutionResult | None = None
    verification_result: VerificationResult | None = None
    overall_status: str = Field(
        description="One of: SUCCESS, REJECTED, VERIFICATION_FAILED, ESCALATED"
    )


class AuditStage(str, Enum):
    """Stages in the incident recovery audit timeline."""
    PROPOSED = "PROPOSED"
    SAFETY_CHECK = "SAFETY_CHECK"
    REJECTED = "REJECTED"
    EXECUTED = "EXECUTED"
    VERIFIED = "VERIFIED"
    ESCALATED = "ESCALATED"


class AuditTimelineEntry(BaseModel):
    """A single record in the immutable audit timeline."""
    id: str
    timestamp: datetime
    stage: AuditStage
    action_type: str
    attempt_number: int
    details: dict[str, Any]
    success: bool

